  /**
   * Test {@link StreamDataImporterColumnInfo#getDataSource()}.
   *
   * <ul>
   *   <li>Then return AvailableInstances size is one.
   * </ul>
   *
   * <p>Method under test: {@link StreamDataImporterColumnInfo#getDataSource()}
   */
  @Test
  @Category(ContributionFromDiffblue.class)
  @ManagedByDiffblue
  @MethodsUnderTest({"DBPDataSource StreamDataImporterColumnInfo.getDataSource()"})
  public void testGetDataSource_thenReturnAvailableInstancesSizeIsOne() {
    // Arrange
    Path inputFile = Paths.get(System.getProperty("java.io.tmpdir"), "test.txt");
    StreamDataImporterColumnInfo streamDataImporterColumnInfo =
        new StreamDataImporterColumnInfo(
            new StreamEntityMapping(inputFile),
            1,
            "Column Name",
            "Type Name",
            3,
            DBPDataKind.BOOLEAN);

    // Act
    DBPDataSource actualDataSource = streamDataImporterColumnInfo.getDataSource();

    // Assert
    Collection<? extends DBSInstance> availableInstances = actualDataSource.getAvailableInstances();
    assertEquals(1, availableInstances.size());
    assertTrue(availableInstances instanceof List);
    assertTrue(
        ((StreamDataSource) actualDataSource).getExclusiveLock() instanceof SimpleExclusiveLock);
    assertTrue(actualDataSource instanceof StreamDataSource);
    DBPDataSourceContainer container = actualDataSource.getContainer();
    assertTrue(container instanceof StreamDataSourceContainer);
    assertTrue(actualDataSource.getSQLDialect() instanceof StreamDataSourceDialect);
    assertEquals("test.txt", actualDataSource.getName());
    assertNull(actualDataSource.getDescription());
    assertEquals(0, ((StreamDataSource) actualDataSource).getAllContexts().length);
    assertFalse(actualDataSource.isConnectionRefreshing());
    assertTrue(actualDataSource.getContextAttributes().isEmpty());
    assertTrue(actualDataSource.isPersisted());
    assertSame(container, actualDataSource.getParentObject());
  }

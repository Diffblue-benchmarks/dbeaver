  @MethodsUnderTest({
    "void StreamDataImporterColumnInfo.<init>(StreamEntityMapping, int, String, String, int, DBPDataKind)"
  })
  public void testNewStreamDataImporterColumnInfo() {
    // Arrange
    Path inputFile = Paths.get(System.getProperty("java.io.tmpdir"), "test.txt");
    StreamEntityMapping entity = new StreamEntityMapping(inputFile);

    // Act
    StreamDataImporterColumnInfo actualStreamDataImporterColumnInfo =
        new StreamDataImporterColumnInfo(
            entity, 1, "Column Name", "Type Name", 3, DBPDataKind.BOOLEAN);

    // Assert
    assertTrue(actualStreamDataImporterColumnInfo.getDataSource() instanceof StreamDataSource);
    assertEquals("Column Name", actualStreamDataImporterColumnInfo.getName());
    assertEquals("Type Name", actualStreamDataImporterColumnInfo.getFullTypeName());
    assertEquals("Type Name", actualStreamDataImporterColumnInfo.getObjectToolTip());
    assertEquals("Type Name", actualStreamDataImporterColumnInfo.getTypeName());
    assertNull(actualStreamDataImporterColumnInfo.getPrecision());
    assertNull(actualStreamDataImporterColumnInfo.getScale());
    assertNull(actualStreamDataImporterColumnInfo.getDescription());
    assertNull(actualStreamDataImporterColumnInfo.getDefaultValue());
    assertEquals(-1, actualStreamDataImporterColumnInfo.getTypeID());
    assertEquals(0L, actualStreamDataImporterColumnInfo.getTypeModifiers());
    assertEquals(1, actualStreamDataImporterColumnInfo.getOrdinalPosition());
    assertEquals(3L, actualStreamDataImporterColumnInfo.getMaxLength());
    assertEquals(DBPDataKind.BOOLEAN, actualStreamDataImporterColumnInfo.getDataKind());
    assertFalse(actualStreamDataImporterColumnInfo.isAutoGenerated());
    assertFalse(actualStreamDataImporterColumnInfo.isRequired());
    assertFalse(actualStreamDataImporterColumnInfo.isMappingMetadataPresent());
    assertTrue(actualStreamDataImporterColumnInfo.isPersisted());
    assertSame(entity, actualStreamDataImporterColumnInfo.getParentObject());
  }


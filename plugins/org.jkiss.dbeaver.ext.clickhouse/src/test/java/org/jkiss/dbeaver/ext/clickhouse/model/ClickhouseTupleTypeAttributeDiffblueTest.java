package org.jkiss.dbeaver.ext.clickhouse.model;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertNull;
import static org.junit.Assert.assertSame;
import static org.junit.Assert.assertTrue;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;
import com.diffblue.cover.annotations.ContributionFromDiffblue;
import com.diffblue.cover.annotations.ManagedByDiffblue;
import com.diffblue.cover.annotations.MethodsUnderTest;
import org.jkiss.dbeaver.model.DBPDataKind;
import org.jkiss.dbeaver.model.struct.DBSDataType;
import org.jkiss.dbeaver.model.struct.DBSEntity;
import org.junit.Test;
import org.junit.experimental.categories.Category;

public class ClickhouseTupleTypeAttributeDiffblueTest {
  /**
   * Test {@link ClickhouseTupleTypeAttribute#ClickhouseTupleTypeAttribute(ClickhouseTupleType,
   * DBSDataType, String, int)}.
   *
   * <ul>
   *   <li>Given one.
   *   <li>Then return {@code Name}.
   * </ul>
   *
   * <p>Method under test: {@link
   * ClickhouseTupleTypeAttribute#ClickhouseTupleTypeAttribute(ClickhouseTupleType, DBSDataType,
   * String, int)}
   */
  @Test
  @Category(ContributionFromDiffblue.class)
  @ManagedByDiffblue
  @MethodsUnderTest({
    "void ClickhouseTupleTypeAttribute.<init>(ClickhouseTupleType, DBSDataType, String, int)"
  })
  public void testNewClickhouseTupleTypeAttribute_givenOne_thenReturnName() {
    // Arrange
    DBSDataType attr = mock(DBSDataType.class);
    when(attr.getTypeID()).thenReturn(1);
    when(attr.getTypeName()).thenReturn("Type Name");

    // Act
    ClickhouseTupleTypeAttribute actualClickhouseTupleTypeAttribute =
        new ClickhouseTupleTypeAttribute(null, attr, "Name", 1);

    // Assert
    verify(attr).getTypeID();
    verify(attr).getTypeName();
    assertEquals("Name", actualClickhouseTupleTypeAttribute.getName());
    assertEquals("Type Name", actualClickhouseTupleTypeAttribute.getTypeName());
    assertNull(actualClickhouseTupleTypeAttribute.getPrecision());
    assertNull(actualClickhouseTupleTypeAttribute.getScale());
    assertNull(actualClickhouseTupleTypeAttribute.getDefaultValue());
    assertNull(actualClickhouseTupleTypeAttribute.getDescription());
    assertNull(actualClickhouseTupleTypeAttribute.getDataKind());
    assertNull(actualClickhouseTupleTypeAttribute.getParentObject());
    assertEquals(-1L, actualClickhouseTupleTypeAttribute.getMaxLength());
    assertEquals(0L, actualClickhouseTupleTypeAttribute.getTypeModifiers());
    assertEquals(1, actualClickhouseTupleTypeAttribute.getOrdinalPosition());
    assertEquals(1, actualClickhouseTupleTypeAttribute.getTypeID());
    assertFalse(actualClickhouseTupleTypeAttribute.isAutoGenerated());
    assertFalse(actualClickhouseTupleTypeAttribute.isRequired());
    assertTrue(actualClickhouseTupleTypeAttribute.isPersisted());
    assertSame(attr, actualClickhouseTupleTypeAttribute.getDataType());
  }

  /**
   * Test {@link ClickhouseTupleTypeAttribute#getParentObject()}.
   *
   * <ul>
   *   <li>Given {@link DBSDataType} {@link DBSDataType#getTypeID()} return one.
   *   <li>Then return {@code null}.
   * </ul>
   *
   * <p>Method under test: {@link ClickhouseTupleTypeAttribute#getParentObject()}
   */
  @Test
  @Category(ContributionFromDiffblue.class)
  @ManagedByDiffblue
  @MethodsUnderTest({"DBSEntity ClickhouseTupleTypeAttribute.getParentObject()"})
  public void testGetParentObject_givenDBSDataTypeGetTypeIDReturnOne_thenReturnNull() {
    // Arrange
    DBSDataType attr = mock(DBSDataType.class);
    when(attr.getTypeID()).thenReturn(1);
    when(attr.getTypeName()).thenReturn("Type Name");
    ClickhouseTupleTypeAttribute clickhouseTupleTypeAttribute =
        new ClickhouseTupleTypeAttribute(null, attr, "Name", 1);

    // Act
    DBSEntity actualParentObject = clickhouseTupleTypeAttribute.getParentObject();

    // Assert
    verify(attr).getTypeID();
    verify(attr).getTypeName();
    assertNull(actualParentObject);
  }

  /**
   * Test {@link ClickhouseTupleTypeAttribute#getDataKind()}.
   *
   * <ul>
   *   <li>Given {@link DBSDataType} {@link DBSDataType#getTypeID()} return one.
   *   <li>Then return {@code BOOLEAN}.
   * </ul>
   *
   * <p>Method under test: {@link ClickhouseTupleTypeAttribute#getDataKind()}
   */
  @Test
  @Category(ContributionFromDiffblue.class)
  @ManagedByDiffblue
  @MethodsUnderTest({"DBPDataKind ClickhouseTupleTypeAttribute.getDataKind()"})
  public void testGetDataKind_givenDBSDataTypeGetTypeIDReturnOne_thenReturnBoolean() {
    // Arrange
    DBSDataType attr = mock(DBSDataType.class);
    when(attr.getTypeID()).thenReturn(1);
    when(attr.getTypeName()).thenReturn("Type Name");
    when(attr.getDataKind()).thenReturn(DBPDataKind.BOOLEAN);
    ClickhouseTupleTypeAttribute clickhouseTupleTypeAttribute =
        new ClickhouseTupleTypeAttribute(null, attr, "Name", 1);

    // Act
    DBPDataKind actualDataKind = clickhouseTupleTypeAttribute.getDataKind();

    // Assert
    verify(attr).getDataKind();
    verify(attr).getTypeID();
    verify(attr).getTypeName();
    assertEquals(DBPDataKind.BOOLEAN, actualDataKind);
  }
}

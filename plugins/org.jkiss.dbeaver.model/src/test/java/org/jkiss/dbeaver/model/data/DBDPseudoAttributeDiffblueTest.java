  /**
   * Test {@link DBDPseudoAttribute#getAttribute(DBDPseudoAttribute[], DBDPseudoAttributeType)}.
   *
   * <ul>
   *   <li>Then return {@code Alias}.
   * </ul>
   *
   * <p>Method under test: {@link DBDPseudoAttribute#getAttribute(DBDPseudoAttribute[],
   * DBDPseudoAttributeType)}
   */
  @Test
  @Category(ContributionFromDiffblue.class)
  @ManagedByDiffblue
  @MethodsUnderTest({
    "DBDPseudoAttribute DBDPseudoAttribute.getAttribute(DBDPseudoAttribute[], DBDPseudoAttributeType)"
  })
  public void testGetAttribute_thenReturnAlias() {
    // Arrange
    DBDPseudoAttribute dbdPseudoAttribute =
        new DBDPseudoAttribute(
            DBDPseudoAttributeType.ROWID,
            "Name",
            "Query Expression",
            "Alias",
            "The characteristics of someone or something",
            true,
            PropagationPolicy.GLOBAL_VARIABLE);

    // Act
    DBDPseudoAttribute actualAttribute =
        DBDPseudoAttribute.getAttribute(
            new DBDPseudoAttribute[] {dbdPseudoAttribute}, DBDPseudoAttributeType.ROWID);

    // Assert
    assertEquals("Alias", actualAttribute.getAlias());
    assertEquals("Name", actualAttribute.getName());
    assertEquals("Query Expression", actualAttribute.getQueryExpression());
    assertEquals("The characteristics of someone or something", actualAttribute.getDescription());
    assertEquals(PropagationPolicy.GLOBAL_VARIABLE, actualAttribute.getPropagationPolicy());
    assertEquals(DBDPseudoAttributeType.ROWID, actualAttribute.getType());
    assertTrue(actualAttribute.isAutoGenerated());
  }


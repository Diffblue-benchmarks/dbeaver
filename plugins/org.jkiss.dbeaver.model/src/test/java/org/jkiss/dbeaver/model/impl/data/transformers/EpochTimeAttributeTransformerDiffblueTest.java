package org.jkiss.dbeaver.model.impl.data.transformers;

import static org.mockito.ArgumentMatchers.isA;
import static org.mockito.Mockito.doNothing;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;
import com.diffblue.cover.annotations.ContributionFromDiffblue;
import com.diffblue.cover.annotations.ManagedByDiffblue;
import com.diffblue.cover.annotations.MethodsUnderTest;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import org.jkiss.dbeaver.DBException;
import org.jkiss.dbeaver.model.data.DBDAttributeBinding;
import org.jkiss.dbeaver.model.data.DBDAttributeBindingCustom;
import org.jkiss.dbeaver.model.data.DBDValueHandler;
import org.jkiss.dbeaver.model.exec.DBCSession;
import org.jkiss.dbeaver.model.impl.data.DefaultValueHandler;
import org.jkiss.dbeaver.model.struct.DBSAttributeBase;
import org.junit.Test;
import org.junit.experimental.categories.Category;
import org.mockito.Mockito;

public class EpochTimeAttributeTransformerDiffblueTest {
  /**
   * Test {@link EpochTimeAttributeTransformer#transformAttribute(DBCSession, DBDAttributeBinding,
   * List, Map)}.
   *
   * <ul>
   *   <li>Given {@code true}.
   *   <li>Then calls {@link DBDAttributeBindingCustom#getValueHandler()}.
   * </ul>
   *
   * <p>Method under test: {@link EpochTimeAttributeTransformer#transformAttribute(DBCSession,
   * DBDAttributeBinding, List, Map)}
   */
  @Test
  @Category(ContributionFromDiffblue.class)
  @ManagedByDiffblue
  @MethodsUnderTest({
    "void EpochTimeAttributeTransformer.transformAttribute(DBCSession, DBDAttributeBinding, List, Map)"
  })
  public void testTransformAttribute_givenTrue_thenCallsGetValueHandler() throws DBException {
    // Arrange
    EpochTimeAttributeTransformer epochTimeAttributeTransformer =
        new EpochTimeAttributeTransformer();
    DBCSession session = mock(DBCSession.class);

    DBDAttributeBindingCustom attribute = mock(DBDAttributeBindingCustom.class);
    when(attribute.isAutoGenerated()).thenReturn(true);
    when(attribute.isRequired()).thenReturn(true);
    when(attribute.getOrdinalPosition()).thenReturn(1);
    when(attribute.getPrecision()).thenReturn(1);
    when(attribute.getScale()).thenReturn(1);
    when(attribute.getName()).thenReturn("Name");
    when(attribute.getMaxLength()).thenReturn(3L);
    when(attribute.getValueHandler()).thenReturn(DefaultValueHandler.INSTANCE);
    doNothing().when(attribute).setPresentationAttribute(Mockito.<DBSAttributeBase>any());
    doNothing().when(attribute).setTransformHandler(Mockito.<DBDValueHandler>any());
    ArrayList<Object[]> rows = new ArrayList<>();

    // Act
    epochTimeAttributeTransformer.transformAttribute(session, attribute, rows, new HashMap<>());

    // Assert
    verify(attribute).getValueHandler();
    verify(attribute).setPresentationAttribute(isA(DBSAttributeBase.class));
    verify(attribute).setTransformHandler(isA(DBDValueHandler.class));
    verify(attribute).getMaxLength();
    verify(attribute).getName();
    verify(attribute).getOrdinalPosition();
    verify(attribute).getPrecision();
    verify(attribute).getScale();
    verify(attribute).isAutoGenerated();
    verify(attribute).isRequired();
  }
}

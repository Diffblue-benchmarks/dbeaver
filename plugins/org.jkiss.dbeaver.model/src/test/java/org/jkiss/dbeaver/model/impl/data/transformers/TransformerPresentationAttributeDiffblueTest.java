package org.jkiss.dbeaver.model.impl.data.transformers;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertNull;
import static org.junit.Assert.assertTrue;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;
import com.diffblue.cover.annotations.ContributionFromDiffblue;
import com.diffblue.cover.annotations.ManagedByDiffblue;
import com.diffblue.cover.annotations.MethodsUnderTest;
import org.jkiss.dbeaver.model.DBPDataKind;
import org.jkiss.dbeaver.model.data.DBDAttributeBinding;
import org.jkiss.dbeaver.model.data.DBDAttributeBindingCustom;
import org.junit.Test;
import org.junit.experimental.categories.Category;

public class TransformerPresentationAttributeDiffblueTest {
  /**
   * Test {@link
   * TransformerPresentationAttribute#TransformerPresentationAttribute(DBDAttributeBinding, String,
   * int, DBPDataKind)}.
   *
   * <ul>
   *   <li>Given {@code true}.
   *   <li>Then return {@code Name}.
   * </ul>
   *
   * <p>Method under test: {@link
   * TransformerPresentationAttribute#TransformerPresentationAttribute(DBDAttributeBinding, String,
   * int, DBPDataKind)}
   */
  @Test
  @Category(ContributionFromDiffblue.class)
  @ManagedByDiffblue
  @MethodsUnderTest({
    "void TransformerPresentationAttribute.<init>(DBDAttributeBinding, String, int, DBPDataKind)"
  })
  public void testNewTransformerPresentationAttribute_givenTrue_thenReturnName() {
    // Arrange
    DBDAttributeBindingCustom attribute = mock(DBDAttributeBindingCustom.class);
    when(attribute.isAutoGenerated()).thenReturn(true);
    when(attribute.isRequired()).thenReturn(true);
    when(attribute.getOrdinalPosition()).thenReturn(1);
    when(attribute.getPrecision()).thenReturn(1);
    when(attribute.getScale()).thenReturn(1);
    when(attribute.getName()).thenReturn("Name");
    when(attribute.getMaxLength()).thenReturn(3L);

    // Act
    TransformerPresentationAttribute actualTransformerPresentationAttribute =
        new TransformerPresentationAttribute(attribute, "Type Name", 1, DBPDataKind.BOOLEAN);

    // Assert
    verify(attribute).getMaxLength();
    verify(attribute).getName();
    verify(attribute).getOrdinalPosition();
    verify(attribute).getPrecision();
    verify(attribute).getScale();
    verify(attribute).isAutoGenerated();
    verify(attribute).isRequired();
    assertEquals("Name", actualTransformerPresentationAttribute.getName());
    assertEquals("Type Name", actualTransformerPresentationAttribute.getTypeName());
    assertNull(actualTransformerPresentationAttribute.getDescription());
    assertEquals(0L, actualTransformerPresentationAttribute.getTypeModifiers());
    assertEquals(1, actualTransformerPresentationAttribute.getPrecision().intValue());
    assertEquals(1, actualTransformerPresentationAttribute.getScale().intValue());
    assertEquals(1, actualTransformerPresentationAttribute.getOrdinalPosition());
    assertEquals(1, actualTransformerPresentationAttribute.getTypeID());
    assertEquals(3L, actualTransformerPresentationAttribute.getMaxLength());
    assertEquals(DBPDataKind.BOOLEAN, actualTransformerPresentationAttribute.getDataKind());
    assertTrue(actualTransformerPresentationAttribute.isAutoGenerated());
    assertTrue(actualTransformerPresentationAttribute.isPersisted());
    assertTrue(actualTransformerPresentationAttribute.isRequired());
  }
}
